const utf8 = new TextEncoder();

function escapeCByte(byte: number, quote: "'" | '"'): string {
  switch (byte) {
    case 0x07:
      return "\\a";
    case 0x08:
      return "\\b";
    case 0x09:
      return "\\t";
    case 0x0a:
      return "\\n";
    case 0x0b:
      return "\\v";
    case 0x0c:
      return "\\f";
    case 0x0d:
      return "\\r";
    case 0x5c:
      return "\\\\";
    case 0x27:
      return quote === "'" ? "\\'" : "'";
    case 0x22:
      return quote === '"' ? '\\"' : '"';
    default:
      if (byte >= 0x20 && byte <= 0x7e) return String.fromCharCode(byte);
      return `\\${byte.toString(8).padStart(3, "0")}`;
  }
}

function cStringLiteral(value: string): string {
  let out = '"';
  for (const byte of utf8.encode(value)) out += escapeCByte(byte, '"');
  return `${out}"`;
}

function cCharLiteral(value: string): string {
  const bytes = utf8.encode(value);
  if (bytes.length !== 1) {
    throw new KixError("character literal must be one byte");
  }
  return `'${escapeCByte(bytes[0]!, "'")}'`;
}

